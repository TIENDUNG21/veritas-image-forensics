// Times the full analysis pipeline on generated JPEGs of 1, 4 and 12 megapixels and writes
// docs/BENCHMARKS.md. Runs in Node on the same code the Web Worker runs.
//
//   node tools/bench.mjs [--runs 5]
import { writeFileSync, mkdirSync } from 'node:fs';
import { cpus, totalmem, platform, release } from 'node:os';
import { parseArgs } from 'node:util';
import { analyzeImage } from '../src/pipeline/analyze.js';
import { landscape } from './fixtures/scene.mjs';
import { encodeJpeg } from './fixtures/jpeg-writer.mjs';

const { values } = parseArgs({ options: { runs: { type: 'string', default: '5' } } });
const RUNS = Number(values.runs);
const SIZES = [
  { label: '1 MP', w: 1224, h: 816 },
  { label: '4 MP', w: 2448, h: 1632 },
  { label: '12 MP', w: 4240, h: 2832 },
];
const STAGES = ['structure', 'decode', 'ela', 'noise', 'gradient', 'copyMove', 'dct'];

/** @param {number[]} xs */
const median = (xs) => [...xs].sort((a, b) => a - b)[Math.floor(xs.length / 2)] ?? 0;

const rows = [];
for (const size of SIZES) {
  const { raster } = landscape(size.w, size.h, 7);
  const bytes = encodeJpeg(raster, { quality: 90 });
  /** @type {Record<string, number[]>} */
  const samples = { total: [] };
  for (let run = 0; run < RUNS + 1; run++) {
    const t0 = performance.now();
    const result = await analyzeImage(bytes, { name: 'bench.jpg' });
    const total = performance.now() - t0;
    if (run === 0) continue; // warm-up: JIT compilation
    samples.total?.push(total);
    for (const stage of STAGES) (samples[stage] ??= []).push(result.timings[stage] ?? 0);
  }
  rows.push({
    ...size,
    bytes: bytes.length,
    total: median(samples.total ?? []),
    stages: Object.fromEntries(STAGES.map((s) => [s, median(samples[s] ?? [])])),
  });
  console.log(`${size.label}: ${Math.round(median(samples.total ?? []))} ms`);
}

const cpu = cpus()[0]?.model.replace(/\s+/g, ' ').trim() ?? 'unknown CPU';
const machine = `${cpu}, ${Math.round(totalmem() / 2 ** 30)} GB RAM, ${platform()} ${release()}, Node ${process.versions.node}`;
const ms = (/** @type {number} */ v) => String(Math.round(v));
const md = `# Benchmarks

Generated by \`node tools/bench.mjs\` (median of ${RUNS} runs after one warm-up run). Each
image is a procedurally generated landscape saved as a baseline JPEG at quality 90, analysed by
the same pipeline the browser runs in its Web Worker, here in Node on one thread.

Machine: ${machine}. Other processes were running; expect a few percent of noise.

| Image | Pixels | File | Total | Parse | Decode | ELA | Noise | Gradient | Copy-move | DCT |
| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |
${rows
  .map(
    (r) =>
      `| ${r.label} | ${r.w} x ${r.h} | ${(r.bytes / 1024 / 1024).toFixed(1)} MB | ${ms(r.total)} ms | ${ms(r.stages.structure ?? 0)} | ${ms(r.stages.decode ?? 0)} | ${ms(r.stages.ela ?? 0)} | ${ms(r.stages.noise ?? 0)} | ${ms(r.stages.gradient ?? 0)} | ${ms(r.stages.copyMove ?? 0)} | ${ms(r.stages.dct ?? 0)} |`,
  )
  .join('\n')}

Stage times are in milliseconds. Copy-move runs on a copy whose longest side is at most
1024 px, so only the downscaling step grows with the image and its cost grows slowly. ELA re-encodes the whole image as JPEG, and decoding
is the project's own Huffman and IDCT code, so both grow linearly with pixel count. The
browser adds the transfer of the result back from the worker and the drawing of the layers,
which are not measured here.
`;
mkdirSync('docs', { recursive: true });
writeFileSync('docs/BENCHMARKS.md', md);
console.log('wrote docs/BENCHMARKS.md');
